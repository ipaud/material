import { app } from 'electron';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { z } from 'zod';
import { parseProject, projectSchema, type Project } from '../../shared/schemas/project';

/**
 * Crash recovery.
 *
 * Autosaves go to userData/recovery/, NEVER to the user's own .material file.
 * A recovery entry records the project's original path (if any) so recovery can
 * tell the user what it belongs to — but restoring only loads it into memory
 * and marks it dirty. Writing back is always an explicit user Save.
 *
 * The file is deleted on clean shutdown, so anything still present at startup
 * means the previous session ended abnormally.
 */

/**
 * The envelope validates strictly, but the embedded project is read as
 * `unknown` and then run through parseProject — which MIGRATES old project
 * versions instead of rejecting them. A crash on v0.1 followed by an upgrade
 * to v0.2 must still offer the autosave, never delete it as "corrupt".
 */
const recoveryEnvelopeSchema = z.object({
  version: z.literal(1),
  sessionId: z.string(),
  savedAt: z.string(),
  projectPath: z.string().nullable(),
  project: z.unknown(),
});

export interface RecoveryEntry {
  version: 1;
  sessionId: string;
  savedAt: string;
  projectPath: string | null;
  project: Project;
}

function recoveryDir(): string {
  return path.join(app.getPath('userData'), 'recovery');
}

function recoveryFile(sessionId: string): string {
  // Session ids are generated by the main process (randomUUID) — never a path.
  return path.join(recoveryDir(), `${sessionId.replace(/[^a-zA-Z0-9-]/g, '')}.json`);
}

export async function writeRecovery(
  sessionId: string,
  projectPath: string | null,
  rawProject: unknown,
): Promise<void> {
  const project = projectSchema.parse(rawProject);
  const entry: RecoveryEntry = {
    version: 1,
    sessionId,
    savedAt: new Date().toISOString(),
    projectPath,
    project,
  };
  await fs.mkdir(recoveryDir(), { recursive: true });
  const target = recoveryFile(sessionId);
  const tmp = `${target}.tmp`;
  await fs.writeFile(tmp, JSON.stringify(entry), 'utf8');
  await fs.rename(tmp, target);
}

export async function clearRecovery(sessionId: string): Promise<void> {
  await fs.rm(recoveryFile(sessionId), { force: true });
}

/** Recovery entries left behind by sessions that did not shut down cleanly. */
export async function listRecoveries(currentSessionId: string): Promise<RecoveryEntry[]> {
  let files: string[];
  try {
    files = await fs.readdir(recoveryDir());
  } catch {
    return [];
  }
  const entries: RecoveryEntry[] = [];
  for (const file of files) {
    if (!file.endsWith('.json')) continue;
    if (file === `${currentSessionId}.json`) continue;
    const filePath = path.join(recoveryDir(), file);
    let envelope: z.infer<typeof recoveryEnvelopeSchema>;
    try {
      envelope = recoveryEnvelopeSchema.parse(JSON.parse(await fs.readFile(filePath, 'utf8')));
    } catch {
      // Unreadable JSON or a broken envelope cannot be offered — but it must
      // not be destroyed either. A truncated autosave is exactly what a kill
      // mid-write produces, which is precisely when the user's work is at
      // stake, and a human may still salvage it by hand. Move it aside so it
      // leaves the scan path without leaving the disk.
      await fs.rename(filePath, `${filePath}.corrupt`).catch(() => undefined);
      continue;
    }
    if (!/^[A-Za-z0-9-]+$/.test(envelope.sessionId) || envelope.sessionId !== file.slice(0, -'.json'.length)) {
      await fs.rename(filePath, `${filePath}.corrupt`).catch(() => undefined);
      continue;
    }
    try {
      // parseProject migrates older project versions (v1 → v2 …).
      entries.push({ ...envelope, project: parseProject(envelope.project) });
    } catch {
      // Envelope is fine but the project does not parse even after migration
      // (e.g. written by a NEWER version). Keep the file — a downgrade must
      // not destroy a future version's autosave — just don't offer it.
    }
  }
  return entries.sort((a, b) => b.savedAt.localeCompare(a.savedAt));
}

export async function discardRecovery(sessionId: string): Promise<void> {
  await clearRecovery(sessionId);
}

export type { Project };
